import fs from "node:fs";
import { Readable } from "node:stream";
import { pipeline } from "node:stream/promises";
import { budgetNote, budgetStatus, monthlyCapUsd, planBudget, PRICE_PER_SECOND, recordSpend, tierFor, type Tier } from "./aiBudget";
import { makeSnapgenClip, snapgenConfigured } from "./snapgen";

/**
 * AI video clips. If a SnapGen key is saved on the Setup page, SnapGen makes every clip first;
 * any clip it fails (error, no credits) falls back to Google's Veo model (the engine behind
 * Google Flow) through the Gemini API key, and then to stock footage in render.ts.
 * Without a SnapGen key, Veo through the Gemini key is used directly. Veo needs billing on the key.
 *
 * Cost control (see aiBudget.ts): the opening hook and key moments use the Fast model, filler
 * shots use the cheaper Lite model, and nothing is generated by Gemini once the monthly budget is
 * spent. The dollar budget only counts Gemini clips; SnapGen is paid in its own credits.
 */

const API = "https://generativelanguage.googleapis.com/v1beta";

/** "fast" (the default) is the smart mix: Fast for the first three shots, Lite for the rest. */
export type AiQuality = Tier;

/** Rough list prices per second of video, for the budget and the cost estimate only. */
export { PRICE_PER_SECOND };
export const CLIP_SECONDS = 8;

const key = () => process.env.GEMINI_API_KEY ?? "";

export async function google(path: string, init?: RequestInit) {
  const res = await fetch(`${API}${path}`, {
    ...init,
    headers: { "Content-Type": "application/json", "x-goog-api-key": key(), ...init?.headers },
  });
  const data = await res.json().catch(() => ({}));
  if (!res.ok) {
    const message: string = data?.error?.message ?? `HTTP ${res.status}`;
    const err = new Error(message) as Error & { status?: number };
    err.status = res.status;
    throw err;
  }
  return data;
}

let models: Promise<string[]> | undefined;

/** Veo models this key can use, newest first (asks Google rather than guessing names). */
function veoModels() {
  models ??= google("/models?pageSize=1000")
    .then((data) =>
      (data.models ?? [])
        .filter((m: any) => /veo/i.test(m.name) && (m.supportedGenerationMethods ?? []).includes("predictLongRunning"))
        .map((m: any) => String(m.name).replace(/^models\//, ""))
        .sort((a: string, b: string) => version(b) - version(a)),
    )
    .catch((err) => {
      models = undefined;
      throw err;
    });
  return models;
}

/** Forgets the cached model list (used by tests). */
export function forgetModels() {
  models = undefined;
}

const version = (name: string) => Number(/veo-(\d+(?:\.\d+)?)/.exec(name)?.[1] ?? 0);

export interface PickedModel {
  model: string;
  /** The tier this model really is, which can differ from the one asked for when it doesn't exist. */
  tier: Tier;
}

/** Which tier to try next when the wanted one isn't offered: cheaper first, the dearest last. */
const FALLBACKS: Record<Tier, Tier[]> = {
  lite: ["lite", "fast", "best"],
  fast: ["fast", "lite", "best"],
  best: ["best", "fast", "lite"],
};

async function pickModel(wanted: Tier): Promise<PickedModel> {
  const list = await veoModels();
  if (!list.length) throw new Error("This Gemini key has no access to Veo video models.");
  const newest = version(list[0]);
  const candidates = list.filter((m) => version(m) === newest);
  const byTier: Record<Tier, string | undefined> = {
    lite: candidates.find((m) => /lite/i.test(m)),
    fast: candidates.find((m) => /fast/i.test(m)),
    best: candidates.find((m) => !/fast|lite/i.test(m)),
  };
  for (const tier of FALLBACKS[wanted]) {
    const model = byTier[tier];
    if (model) return { model, tier };
  }
  return { model: list[0], tier: "fast" };
}

/** Starts a clip; returns the operation name to poll. */
async function start(model: string, prompt: string, portrait: boolean) {
  const body = (aspectRatio: string) =>
    JSON.stringify({
      instances: [{ prompt }],
      parameters: {
        aspectRatio,
        negativePrompt: "text, captions, subtitles, watermark, logo, modern clothing, cartoon, low quality, distorted faces",
      },
    });
  for (let attempt = 0; ; attempt++) {
    try {
      const op = await google(`/models/${model}:predictLongRunning`, {
        method: "POST",
        body: body(portrait ? "9:16" : "16:9"),
      });
      return op.name as string;
    } catch (err) {
      const e = err as Error & { status?: number };
      // Some Veo versions only make landscape clips; those get cropped to fit instead.
      if (portrait && e.status === 400 && /aspect/i.test(e.message)) {
        const op = await google(`/models/${model}:predictLongRunning`, { method: "POST", body: body("16:9") });
        return op.name as string;
      }
      if (e.status === 429 && attempt < 3) {
        await sleep(30_000);
        continue;
      }
      throw err;
    }
  }
}

/** Waits for a clip and downloads it. */
async function finish(operation: string, outFile: string) {
  const deadline = Date.now() + 8 * 60 * 1000;
  for (;;) {
    const op = await google(`/${operation}`);
    if (op.done) {
      if (op.error) throw new Error(op.error.message ?? "Veo failed.");
      const response = op.response?.generateVideoResponse ?? op.response;
      const sample = response?.generatedSamples?.[0] ?? response?.generatedVideos?.[0];
      const uri: string | undefined = sample?.video?.uri;
      if (!uri) {
        const reason = response?.raiMediaFilteredReasons?.[0];
        throw new Error(reason ? `Veo blocked this shot: ${reason}` : "Veo returned no video.");
      }
      const res = await fetch(uri, { headers: { "x-goog-api-key": key() } });
      if (!res.ok || !res.body) throw new Error(`Couldn't download the Veo clip (${res.status}).`);
      await pipeline(Readable.fromWeb(res.body as any), fs.createWriteStream(outFile));
      return;
    }
    if (Date.now() > deadline) throw new Error("Veo took too long.");
    await sleep(10_000);
  }
}

export interface ClipRequest {
  prompt: string;
  outFile: string;
}

/**
 * Makes several clips. Returns, per request, true when the clip was made or the reason it
 * wasn't (so the caller can fall back to stock footage for that shot).
 * Requests are in order of importance: the first is the opening hook.
 *
 * With a SnapGen key, SnapGen goes first and Gemini Veo only covers the clips it failed.
 * A monthly AI footage budget of $0 switches AI footage off completely, SnapGen included.
 */
export async function makeClips(
  requests: ClipRequest[],
  quality: AiQuality,
  portrait: boolean,
  onProgress: (done: number) => void,
): Promise<(true | string)[]> {
  if (!snapgenConfigured() || monthlyCapUsd() === 0) return makeGeminiClips(requests, quality, portrait, onProgress);

  const results: (true | string)[] = new Array(requests.length).fill("SnapGen didn't run.");
  let next = 0;
  let done = 0;
  const worker = async () => {
    while (next < requests.length) {
      const i = next++;
      try {
        await makeSnapgenClip(requests[i].prompt, requests[i].outFile, tierFor(quality, i), portrait);
        results[i] = true;
        onProgress(++done);
      } catch (err) {
        results[i] = (err as Error).message;
        console.warn(`[AI footage] SnapGen failed for shot ${i + 1}: ${(err as Error).message}`);
      }
    }
  };
  await Promise.all([worker(), worker()]);

  // Whatever SnapGen couldn't make goes to Gemini Veo (when a Gemini key is set), then stock footage.
  const failed = results.flatMap((r, i) => (r === true ? [] : [i]));
  if (!failed.length) return results;
  if (!key()) {
    for (const i of failed) results[i] = `${results[i]} No Gemini key is set as a backup.`;
    return results;
  }
  console.log(`[AI footage] ${failed.length} clip(s) fall back to Gemini Veo.`);
  const backup = await makeGeminiClips(
    failed.map((i) => requests[i]),
    quality,
    portrait,
    (n) => onProgress(done + n),
    failed,
  );
  failed.forEach((i, k) => {
    results[i] = backup[k] === true ? true : `${results[i]} Gemini backup: ${backup[k]}`;
  });
  return results;
}

/**
 * Veo through the Gemini key, two clips at a time, inside the monthly budget.
 * `positions` are the clips' places in the whole video (so the hook keeps the better model).
 */
async function makeGeminiClips(
  requests: ClipRequest[],
  quality: AiQuality,
  portrait: boolean,
  onProgress: (done: number) => void,
  positions: number[] = requests.map((_, i) => i),
): Promise<(true | string)[]> {
  // Resolve the real model for each tier we might use (the cheapest is the budget's fallback).
  const picked = new Map<Tier, PickedModel>();
  try {
    const wanted = positions.map((p) => tierFor(quality, p));
    for (const tier of new Set<Tier>([...wanted, "lite"])) picked.set(tier, await pickModel(tier));
  } catch (err) {
    return requests.map(() => `AI footage unavailable: ${(err as Error).message}`);
  }

  // Plan the whole video against what is left of this month's budget.
  const wanted = positions.map((p) => picked.get(tierFor(quality, p))!.tier);
  const cheapest = picked.get("lite")!;
  const plan = planBudget(wanted, CLIP_SECONDS, budgetStatus().remainingUsd, cheapest.tier);
  const choice = plan.map((tier, i) =>
    tier === null ? null : tier === wanted[i] ? picked.get(tierFor(quality, positions[i]))! : cheapest,
  );
  const cut = choice.filter((c) => c === null).length;
  const stepped = choice.filter((c, i) => c && c.tier !== wanted[i]).length;
  if (cut || stepped) console.log(`[AI footage] Budget: ${stepped} clip(s) moved to the cheaper model, ${cut} skipped.`);

  const results: (true | string)[] = new Array(requests.length);
  let next = 0;
  let done = 0;
  const worker = async () => {
    while (next < requests.length) {
      const i = next++;
      const pick = choice[i];
      const cost = pick ? CLIP_SECONDS * PRICE_PER_SECOND[pick.tier] : 0;
      // Checked again just before each clip: a long video shouldn't overshoot the budget.
      if (!pick || budgetStatus().remainingUsd + 1e-9 < cost) {
        results[i] = budgetNote();
      } else {
        try {
          const op = await start(pick.model, requests[i].prompt, portrait);
          await finish(op, requests[i].outFile);
          recordSpend(cost, { tier: pick.tier, model: pick.model });
          results[i] = true;
        } catch (err) {
          results[i] = (err as Error).message;
        }
      }
      onProgress(++done);
    }
  };
  await Promise.all([worker(), worker()]);
  return results;
}

const sleep = (ms: number) => new Promise((r) => setTimeout(r, ms));
